object AppSettings { var dark by mutableStateOf(false) }

@Composable
fun FindBackTheme(dark: Boolean, content: @Composable () -> Unit) {
    val scheme = if (dark) darkColorScheme(primary = Green, secondary = Green)
    else lightColorScheme(primary = Green, secondary = Green, background = AppBg, surface = Color.White)
    MaterialTheme(colorScheme = scheme, content = content)
}
